export function getSalaryBracketLabel(
  currency: string,
  key: string,
  locale: Locale,
): string {
  return (
    SALARY_BRACKET_LABELS[currency]?.[key]?.[locale] ||
    SALARY_BRACKET_LABELS[currency]?.[key]?.en ||
    key
  );
}

export function findSelectedBracketKey(
  currency: string,
  min: number,
  max: number,
): string | null {
  const brackets = SALARY_BRACKETS[currency] || SALARY_BRACKETS["USD"];
  const match = brackets.find((b) => b.min === min && b.max === max);
  return match?.key || null;
}

export function getIndustryLabel(key: string, locale: Locale): string {
  const industry = INDUSTRIES.find((i) => i.id === key);
  if (industry) {
    return getIndustryLabelByLocale(industry, locale);
  }
  return key;
}

