// ============================================================
// Session summary — Phase 4 longitudinal memory generation.
//
// After a coaching conversation ends, distill a structured summary so the next
// session can continue instead of restarting cold. Reuses the existing
// "coaching-summary" LLM task (NOT a new model-router task — that file is
// frozen). Fire-and-forget + fail-soft: any error is swallowed, since
// cross-session memory is strictly additive.
//
// @language-guard-exempt: returns internal JSON memory only; the prompt pins
// output to the request locale, and user-visible coaching text is generated by
// the guarded coaching stream.
// ============================================================

import { z } from "zod/v4";
import { callLLMStructured } from "@/lib/ai/structured-output";
import { getEmbedding, isEmbeddingAvailable } from "@/lib/ai/embeddings";
import { saveSessionSummary } from "@/lib/db/coaching-session-summary";

interface ChatMessage {
  role: string;
  content: string;
}

const SessionSummarySchema = z.object({
  summary: z.string(),
  keyDecisions: z.array(z.string()),
  openLoops: z.array(z.string()),
  emotionalArc: z.string().nullable(),
});

function buildSummaryMessages(
  messages: ChatMessage[],
  locale: string,
): { role: "system" | "user"; content: string }[] {
  const isZh = locale === "zh";
  // Bound the transcript: the request schema allows up to ~100 × 4000 chars,
  // which would overflow the summary LLM context and then fail silently. Cap
  // each message, and cap the total while keeping the MOST RECENT exchanges
  // (recency matters most for cross-session continuity).
  const MAX_MSG_CHARS = 2000;
  const MAX_TRANSCRIPT_CHARS = 24000;
  let transcript = messages
    .map((m) => {
      const content =
        m.content.length > MAX_MSG_CHARS
          ? `${m.content.slice(0, MAX_MSG_CHARS)}…`
          : m.content;
      return `${m.role}: ${content}`;
    })
    .join("\n\n");
  if (transcript.length > MAX_TRANSCRIPT_CHARS) {
    const prefix = "…\n\n";
    transcript =
      prefix + transcript.slice(-(MAX_TRANSCRIPT_CHARS - prefix.length));
  }

  const system = isZh
    ? `你是职业教练的记忆系统。根据下面这次教练对话,提炼一份结构化摘要,供下次对话延续上下文。只提炼用户真实表达的内容,不要编造。
输出 JSON,字段:
- summary: 2-4 句话概括这次谈了什么、用户的核心立场
- keyDecisions: 用户做出的决定或明显倾向(字符串数组,没有则 [])
- openLoops: 未解决的张力、纠结或待办(字符串数组,没有则 [])
- emotionalArc: 这次对话的情绪走向(一句话,如"从焦虑到稍微清晰";没有明显情绪则 null)
全部用简体中文。`
    : `You are the memory system for a career coach. From the coaching conversation below, distill a structured summary so the next session can continue with context. Only capture what the user actually expressed — do not invent.
Output JSON with fields:
- summary: 2-4 sentences on what was discussed and the user's core stance
- keyDecisions: decisions or clear leanings the user made (array of strings, [] if none)
- openLoops: unresolved tensions, dilemmas, or to-dos (array of strings, [] if none)
- emotionalArc: one sentence on the emotional trajectory (e.g. "from anxious to a bit clearer"); null if no clear emotion
Respond entirely in English.`;

  return [
    { role: "system", content: system },
    { role: "user", content: transcript },
  ];
}

export async function summarizeAndStoreSession(
  userId: string,
  sessionId: string,
  messages: ChatMessage[],
  locale: string,
): Promise<void> {
  try {
    // Too short to be worth summarizing (greeting + one exchange).
    if (messages.filter((m) => m.role === "user").length < 2) return;

    const parsed = await callLLMStructured(
      "coaching-summary",
      buildSummaryMessages(messages, locale),
      SessionSummarySchema,
      {
        responseFormat: "json",
        temperature: 0.2,
        maxTokens: 600,
        timeoutMs: 15_000,
      },
    );

    let embedding: number[] | null = null;
    if (isEmbeddingAvailable()) {
      try {
        embedding = await getEmbedding(parsed.summary);
      } catch {
        // leave NULL — retrieveRelevantSummaries skips it, getRecentSummaries still works
      }
    }

    await saveSessionSummary({
      userId,
      sessionId,
      summary: parsed.summary,
      keyDecisions: parsed.keyDecisions,
      openLoops: parsed.openLoops,
      emotionalArc: parsed.emotionalArc,
      embedding,
    });
  } catch (err) {
    console.warn(
      "[session-summary] generation failed, skipping:",
      err instanceof Error ? err.message : err,
    );
  }
}
