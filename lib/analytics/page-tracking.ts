/**
 * Derive device type from user-agent string.
 * Returns 'mobile' | 'tablet' | 'desktop'
 */
function detectDeviceType(userAgent: string | null): 'mobile' | 'tablet' | 'desktop' {
  if (!userAgent) return 'desktop';
  if (/iPad|Tablet/i.test(userAgent)) return 'tablet';
  if (/Mobile|Android/i.test(userAgent)) return 'mobile';
  return 'desktop';
}

/**
 * Record a page visit. Fire-and-forget — failures are logged but never thrown.
 * Called from middleware on page (non-API, non-static) GET requests.
 *
 * visitId is pre-generated by the caller (middleware) so it can be returned
 * to the client as a cookie before the async insert completes.
 */
/**
 * SHA-256 hash of IP (exported for reuse in admin API routes).
 * Truncated to first 16 hex chars — sufficient for grouping, not reversible.
 */
export async function hashIPAddress(ip: string): Promise<string> {
  return hashIP(ip);
}

export async function trackPageVisit(opts: {
  visitId: string;
  path: string;
  ip: string | null;
  userAgent: string | null;
  referer: string | null;
  userId: string | null;
  country: string | null;
  city: string | null;
  region: string | null;
  timezone: string | null;
  isMobile: boolean | null;
  platform: string | null;
  acceptLanguage: string | null;
  deviceType: 'mobile' | 'tablet' | 'desktop' | null;
  utmSource: string | null;
  utmMedium: string | null;
  utmCampaign: string | null;
  utmContent: string | null;
  visitSessionId: string | null;
}): Promise<void> {
  try {
    const { visitId, path, ip, userAgent, referer, userId, country, city, region, timezone,
            isMobile, platform, acceptLanguage, deviceType,
            utmSource, utmMedium, utmCampaign, utmContent, visitSessionId } = opts;
    const ipHash = ip ? await hashIP(ip) : null;

    // Skip tracking for IP hashes explicitly excluded by the owner (env var)
    const excludedHashes = (process.env.EXCLUDED_IP_HASHES || '').split(',').filter(Boolean);
    if (ipHash && excludedHashes.includes(ipHash)) return;

    const { isBot } = detectBot(userAgent);
    if (isBot) return; // Skip DB write for bot traffic — saves ~96% of PageVisit volume

    const { isInternal } = detectInternalTraffic({ referer, userAgent });

    // userId is resolved and admin-filtered upstream by middleware (schedulePageTracking).
    // No secondary UserSession lookup needed here.

    await sql`
      INSERT INTO "PageVisit" (
        "id", "path", "ipHash", "userAgent", "referer", "userId", "country", "isBot", "isInternal",
        "city", "region", "timezone", "isMobile", "platform", "acceptLanguage", "deviceType",
        "utmSource", "utmMedium", "utmCampaign", "utmContent", "visitSessionId"
      )
      VALUES (
        ${visitId},
        ${path},
        ${ipHash},
        ${userAgent ? userAgent.slice(0, 512) : null},
        ${referer ? referer.slice(0, 1024) : null},
        ${userId},
        ${country},
        ${false},
        ${isInternal},
        ${city},
        ${region},
        ${timezone},
        ${isMobile},
        ${platform ? platform.slice(0, 100) : null},
        ${acceptLanguage ? acceptLanguage.slice(0, 100) : null},
        ${deviceType},
        ${utmSource},
        ${utmMedium},
        ${utmCampaign},
        ${utmContent},
        ${visitSessionId}
      )
    `;
  } catch (error) {
    await logAnalyticsError('page_visit', null, error);
  }
}

/**
 * Update the dwell time for an existing visit record.
 * Called by /api/analytics/duration when the user leaves the page.
 */
export async function updateVisitDuration(visitId: string, durationMs: number): Promise<void> {
  try {
    await sql`
      UPDATE "PageVisit" SET "durationMs" = ${durationMs}
      WHERE "id" = ${visitId} AND "durationMs" IS NULL
    `;
  } catch {
    // Silently ignore — duration is a best-effort metric
  }
}

